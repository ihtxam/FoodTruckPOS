const dictionaries: Record<Locale, Dict> = { en, fr, de };

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function isLocale(value: unknown): value is Locale {
  return value === 'en' || value === 'fr' || value === 'de';
}

export function detectBrowserLocale(): Locale {
  try {
    const lang = (navigator.language || '').toLowerCase();
    if (lang.startsWith('fr')) return 'fr';
    if (lang.startsWith('de')) return 'de';
  } catch {
    // ignore
  }
  return 'en';
}

export function I18nProvider({
  children,
  initialLocale,
  storageKey = PANEL_LANG_KEY,
}: {
  children: ReactNode;
  initialLocale?: Locale;
  /** Separate keys so merchant panel language ≠ customer shop language */
  storageKey?: string;
}) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    try {
      const stored = localStorage.getItem(storageKey);
      if (isLocale(stored)) return stored;
    } catch {
      // ignore
    }
    if (isLocale(initialLocale)) return initialLocale;
    return storageKey === SHOP_LANG_KEY ? detectBrowserLocale() : 'en';
  });

  const setLocale = useCallback(
    (next: Locale) => {
      if (!isLocale(next)) return;
      setLocaleState(next);
      try {
        localStorage.setItem(storageKey, next);
      } catch {
        // ignore
      }
    },
    [storageKey]
  );

  useEffect(() => {
    if (!isLocale(initialLocale)) return;
    try {
      const stored = localStorage.getItem(storageKey);
      if (!isLocale(stored)) {
        setLocaleState(initialLocale);
        localStorage.setItem(storageKey, initialLocale);
      }
    } catch {
      setLocaleState(initialLocale);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [initialLocale, storageKey]);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo(
    () => ({
      locale,
      setLocale,
      t: (key: string) => dictionaries[locale][key] || dictionaries.en[key] || key,
    }),
    [locale, setLocale]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    return {
      locale: 'en' as Locale,
      setLocale: (_locale: Locale) => undefined,
      t: (key: string) => dictionaries.en[key] || key,
    };
  }
  return ctx;
}
